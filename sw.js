// A classic script, not a module (docs/CONVENTIONS.md): no `import`/`export`.
// Registered from js/app.js as `./sw.js`, so its scope is the app's directory
// (`/flags/` on GitHub Pages, `/` locally).
//
// Caching:
//   - `install` downloads every file in `PRECACHE_FILES` into one cache named
//     after `CACHE_VERSION`, then calls `skipWaiting()`. Each file is fetched
//     as `<path>?v=<CACHE_VERSION>` with `cache: 'reload'`: the query string
//     gets past Pages' CDN, which may still hold the previous deploy's copy
//     for a while after a push, and `reload` past the HTTP cache. Every body
//     must match the SHA-256 recorded for it, or the install fails (and the
//     browser tries again on a later update check) instead of caching an old
//     file under the new version. It is stored under the clean URL.
//   - `activate` deletes every other cache with this app's prefix (and no
//     one else's: all of a user's Pages projects share one origin), then
//     `clients.claim()`.
//   - `fetch` is cache-first for same-origin GETs in scope. App-shell
//     navigations (`./`, `./index.html`) get the cached `index.html`; other
//     navigations try the cache, then the network, then fall back to it.
//     Cross-origin requests are never intercepted (the app makes none).
//   - Only `install` writes to the cache, and only responses that are `ok`,
//     `basic` (same-origin, not opaque) and not redirected. Responses fetched
//     at run time are passed through, never stored: everything the app needs
//     is precached, so a file missing from the list breaks offline visibly
//     instead of working by luck.
//
// Versioning: the block below is written by `node scripts/build-sw.js`.
// `CACHE_VERSION` is a content hash of every precached file, so any change
// to the app gives a new cache name (and a byte-different `sw.js`, which is
// what makes browsers install the new worker). test/sw.test.js fails if the
// block is stale.
//
// js/app.js reloads the page when a new worker takes over, but only on the
// home screen, never mid-round or mid-test.

