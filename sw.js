const CACHE_PREFIX = 'flags-precache-';
const CACHE_NAME = `${CACHE_PREFIX}${CACHE_VERSION}`;
const SCOPE_URL = new URL(self.registration.scope);
const INDEX_URL = new URL('./index.html', SCOPE_URL).href;

function isCacheable(response) {
  return response.ok && response.type === 'basic' && !response.redirected;
}

// Content types by extension, for a response that arrives without one.
const CONTENT_TYPES = Object.freeze({
  '.css': 'text/css',
  '.html': 'text/html',
  '.js': 'text/javascript',
  '.json': 'application/json',
  '.png': 'image/png',
  '.svg': 'image/svg+xml',
  '.webmanifest': 'application/manifest+json'
});

function getContentType(response, url) {
  const header = response.headers.get('Content-Type');
  if (header !== null && header !== '') {
    return header;
  }
  const extension = url.pathname.match(/\.[a-z]+$/)?.[0] ?? '';
  return CONTENT_TYPES[extension] ?? 'application/octet-stream';
}

function toHex(buffer) {
  return [...new Uint8Array(buffer)].map((byte) => byte.toString(16).padStart(2, '0')).join('');
}

// A failed install deliberately leaves its (partial) cache alone: after a
// change to sw.js alone, `CACHE_NAME` is also the live worker's cache, and
// deleting it would empty the app. The next successful install overwrites
// every entry, and a later version's `activate` deletes it.
async function precache() {
  const cache = await caches.open(CACHE_NAME);
  await Promise.all(PRECACHE_FILES.map(async ([path, sha256]) => {
    const url = new URL(path, SCOPE_URL);
    const busted = new URL(url);
    busted.searchParams.set('v', CACHE_VERSION);
    const response = await fetch(busted.href, { cache: 'reload' });
    if (!isCacheable(response)) {
      throw new Error(`Precaching ${path} failed (HTTP ${response.status}, type ${response.type}).`);
    }
    const body = await response.arrayBuffer();
    const digest = toHex(await crypto.subtle.digest('SHA-256', body));
    if (digest !== sha256) {
      throw new Error(`Precaching ${path} failed: its content does not match this version (stale copy?).`);
    }
    // A fresh Response, so the cached one carries no `?v=` URL. Only
    // `Content-Type` is copied: `body` is the decoded bytes, while Pages
    // serves gzip, so its `Content-Encoding` and (compressed)
    // `Content-Length` would describe a different body, which WebKit has
    // mishandled in cached responses (truncation, decode errors).
    await cache.put(url.href, new Response(body, {
      status: response.status,
      headers: { 'Content-Type': getContentType(response, url) }
    }));
  }));
}

async function deleteOldCaches() {
  const names = await caches.keys();
  await Promise.all(names
    .filter((name) => name.startsWith(CACHE_PREFIX) && name !== CACHE_NAME)
    .map((name) => caches.delete(name)));
}

function isAppShell(url) {
  return url.pathname === SCOPE_URL.pathname || url.href.split(/[?#]/)[0] === INDEX_URL;
}

// `caches.match` with `cacheName` rather than `caches.open`: an old worker
// still finishing a request must not recreate a cache `activate` deleted.
async function respond(request) {
  const options = { cacheName: CACHE_NAME };
  if (request.mode !== 'navigate') {
    return (await caches.match(request, options)) ?? fetch(request);
  }
  const url = new URL(request.url);
  const cached = isAppShell(url)
    ? await caches.match(INDEX_URL, options)
    : await caches.match(request, { ...options, ignoreSearch: true });
  if (cached !== undefined) {
    return cached;
  }
  try {
    return await fetch(request);
  } catch (error) {
    const fallback = await caches.match(INDEX_URL, options);
    if (fallback !== undefined) {
      return fallback;
    }
    throw error;
  }
}

self.addEventListener('install', (event) => {
  event.waitUntil(precache().then(() => self.skipWaiting()));
});

self.addEventListener('activate', (event) => {
  event.waitUntil(deleteOldCaches().then(() => self.clients.claim()));
});

self.addEventListener('fetch', (event) => {
  const { request } = event;
  if (request.method !== 'GET') {
    return;
  }
  const url = new URL(request.url);
  // Same origin but another Pages project (`/other/`) is not ours either.
  if (url.origin !== SCOPE_URL.origin || !url.href.startsWith(SCOPE_URL.href)) {
    return;
  }
  // DevTools can issue these; `fetch` would throw on them.
  if (request.cache === 'only-if-cached' && request.mode !== 'same-origin') {
    return;
  }
  event.respondWith(respond(request));
});
