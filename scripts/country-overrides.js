/**
 * Sovereign state (UN member or observer).
 * @param {string} name
 * @param {string} region
 * @param {string[]} [aliases]
 * @returns {{name: string, aliases: string[], region: string, sovereign: boolean, parentCode: null}}
 */
function state(name, region, aliases = []) {
  return { name, aliases, region, sovereign: true, parentCode: null };
}

/**
 * Non-sovereign entry: a dependency/territory (`parentCode` set) or an entry
 * with disputed status (`parentCode` null).
 * @param {string} name
 * @param {string} region
 * @param {string | null} parentCode
 * @param {string[]} [aliases]
 * @returns {{name: string, aliases: string[], region: string, sovereign: boolean, parentCode: string | null}}
 */
function territory(name, region, parentCode, aliases = []) {
  return { name, aliases, region, sovereign: false, parentCode };
}

